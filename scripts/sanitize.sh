#!/usr/bin/env bash
# =============================================================================
# sanitize.sh - makes the working tree safe to commit to a public repository.
#
# Running the labs leaves project-specific values behind:
#   - env.sh holds your PROJECT_ID (and possibly a custom PREFIX or allow-list),
#   - envsubst renders manifests that contain your project ID and registry path
#     (05-deploy-app/online-boutique/kustomization.yaml, **/rendered/),
#   - Lab 04 writes a private key to tls/, the Terraform appendix writes
#     terraform.tfvars and terraform.tfstate.
#
# What this script does, in this order:
#   1. .gitignore: adds any missing pattern for the generated files.
#   2. env.sh: resets the "EDIT THESE" values to the documented defaults
#      (a copy of your values is kept in env.sh.local, which git ignores).
#   3. Generated files: checks that every file the labs generate is ignored by
#      git and not tracked; untracks any that slipped in (the file stays on disk).
#   4. --purge only: deletes the rendered manifests (they are regenerated by the
#      labs). tls/, terraform.tfvars, terraform.tfstate and .terraform/ are never
#      deleted: you need them until the cleanup.
#   5. Scans every file git would commit (tracked + untracked, not ignored) for
#      project IDs, project numbers, e-mail addresses, public IP addresses,
#      private keys, Google credentials and cluster-generated resource names.
#
# Usage (from the repository root):
#   ./scripts/sanitize.sh            fix what can be fixed, then report
#   ./scripts/sanitize.sh --check    report only, change nothing (pre-commit / CI)
#   ./scripts/sanitize.sh --purge    like the default, plus delete rendered manifests
#   ./scripts/sanitize.sh --yes      don't ask before deleting (with --purge)
#
# Exit codes: 0 clean, 1 findings remain (content that needs a manual edit), 2 usage.
# Works with bash 3.2 (macOS) and bash 5 (Cloud Shell).
# =============================================================================
set -uo pipefail
export LC_ALL=C

MODE="fix"; PURGE=0; YES=0
for arg in "$@"; do
  case "${arg}" in
    --check) MODE="check" ;;
    --purge) PURGE=1 ;;
    --yes|-y) YES=1 ;;
    -h|--help) sed -n '2,32p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "Unknown option: ${arg} (try --help)" >&2; exit 2 ;;
  esac
done

ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || { echo "ERROR: run this inside the repository." >&2; exit 2; }
cd "${ROOT}"

FINDINGS=0; FIXED=0; WARNINGS=0
ok()      { printf '  [OK]      %s\n' "$1"; }
fixed()   { printf '  [FIXED]   %s\n' "$1"; FIXED=$((FIXED + 1)); }
finding() { printf '  [FINDING] %s\n' "$1"; FINDINGS=$((FINDINGS + 1)); }
warn()    { printf '  [WARN]    %s\n' "$1"; WARNINGS=$((WARNINGS + 1)); }
section() { printf '\n%s\n' "$1"; }

# Files the labs generate. Regenerable ones can be purged; the others are only checked.
REGENERABLE="05-deploy-app/online-boutique/kustomization.yaml
06-cluster-security/policies/rendered
08-cluster-monitoring/alerting/rendered"
KEEP="tls
appendix-terraform/terraform.tfvars
appendix-terraform/terraform.tfstate
appendix-terraform/terraform.tfstate.backup
appendix-terraform/.terraform
env.sh.local"

# .gitignore patterns that must exist (pattern|what it covers)
REQUIRED_IGNORES="05-deploy-app/online-boutique/kustomization.yaml|rendered Kustomize overlay (Lab 05)
**/rendered/|rendered policies and alert definitions (Labs 06, 08)
tls/|self-signed certificate and private key (Lab 04)
*.key|private keys
*.crt|certificates
*.pem|keys and certificates
*.tfvars|Terraform inputs with your project ID
*.tfstate|Terraform state
*.tfstate.*|Terraform state backups
.terraform/|Terraform providers and modules
env.sh.local|your env.sh values, saved by scripts/sanitize.sh
kubeconfig*|kubectl credentials
*credentials*.json|downloaded credentials
*service-account*.json|service account keys"

# env.sh documented defaults (VAR|default)
ENV_DEFAULTS="PROJECT_ID|REPLACE_WITH_YOUR_PROJECT_ID
PREFIX|gkews
REGION|asia-southeast1
ALLOWED_EGRESS_FQDNS|ifconfig.me,api.github.com"

env_value() { sed -n -E "s/^export $1=\"([^\"]*)\".*/\1/p" env.sh | head -1; }

# ---------------------------------------------------------------- 0. identifiers to look for
# Collected before env.sh is reset: your project ID from env.sh, terraform.tfvars, the rendered
# overlay and the gcloud configuration (local file read, no API call).
IDS=""
add_id() { case "$1" in ""|REPLACE_WITH_YOUR_PROJECT_ID|"(unset)") ;; *) case " ${IDS} " in *" $1 "*) ;; *) IDS="${IDS} $1" ;; esac ;; esac; }
add_id "$(env_value PROJECT_ID)"
[ -f appendix-terraform/terraform.tfvars ] && add_id "$(sed -n -E 's/^project_id *= *"([^"]*)".*/\1/p' appendix-terraform/terraform.tfvars | head -1)"
[ -f 05-deploy-app/online-boutique/kustomization.yaml ] && add_id "$(sed -n -E 's#.*-docker\.pkg\.dev/([a-z][a-z0-9-]+)/.*#\1#p' 05-deploy-app/online-boutique/kustomization.yaml | head -1)"
if command -v gcloud >/dev/null 2>&1; then add_id "$(gcloud config get-value project 2>/dev/null || true)"; fi

section "Identifiers to look for"
if [ -n "${IDS}" ]; then ok "project ID(s):${IDS}"; else warn "no project ID found in env.sh, terraform.tfvars, the rendered overlay or gcloud config; scanning with generic patterns only"; fi

# ---------------------------------------------------------------- 1. .gitignore (first, so files created below are ignored)
section "1. .gitignore"
MISSING=""
while IFS='|' read -r PATTERN WHAT; do
  [ -z "${PATTERN}" ] && continue
  if grep -qxF -- "${PATTERN}" .gitignore 2>/dev/null; then :; else MISSING="${MISSING}${PATTERN}|${WHAT}
"; fi
done <<EOF
${REQUIRED_IGNORES}
EOF
if [ -z "${MISSING}" ]; then
  ok ".gitignore covers every generated file"
elif [ "${MODE}" = "check" ]; then
  while IFS='|' read -r PATTERN WHAT; do [ -n "${PATTERN}" ] && finding ".gitignore is missing: ${PATTERN}  (${WHAT})"; done <<EOF
${MISSING}
EOF
else
  { echo; echo "# Added by scripts/sanitize.sh"; } >> .gitignore
  while IFS='|' read -r PATTERN WHAT; do
    [ -z "${PATTERN}" ] && continue
    echo "${PATTERN}" >> .gitignore && fixed ".gitignore: added ${PATTERN}  (${WHAT})"
  done <<EOF
${MISSING}
EOF
fi

# ---------------------------------------------------------------- 2. env.sh
section "2. env.sh"
ENV_CHANGES=""
while IFS='|' read -r VAR DEFAULT; do
  [ -z "${VAR}" ] && continue
  CURRENT="$(env_value "${VAR}")"
  if [ "${CURRENT}" != "${DEFAULT}" ]; then ENV_CHANGES="${ENV_CHANGES}${VAR}=${CURRENT} -> ${DEFAULT}
"; fi
done <<EOF
${ENV_DEFAULTS}
EOF
if [ -z "${ENV_CHANGES}" ]; then
  ok "env.sh has the documented defaults"
elif [ "${MODE}" = "check" ]; then
  while IFS= read -r line; do [ -n "${line}" ] && finding "env.sh: ${line}"; done <<EOF
${ENV_CHANGES}
EOF
else
  cp env.sh env.sh.local
  while IFS='|' read -r VAR DEFAULT; do
    [ -z "${VAR}" ] && continue
    sed -E "s|^(export ${VAR}=\")[^\"]*(\".*)$|\1${DEFAULT}\2|" env.sh > env.sh.tmp && mv env.sh.tmp env.sh
  done <<EOF
${ENV_DEFAULTS}
EOF
  while IFS= read -r line; do [ -n "${line}" ] && fixed "env.sh: ${line}"; done <<EOF
${ENV_CHANGES}
EOF
  warn "your values are in env.sh.local (ignored by git). Restore them with: cp env.sh.local env.sh"
fi

# ---------------------------------------------------------------- 3. generated files: ignored and untracked?
section "3. Generated files"
check_generated() {  # $1 path, $2 "regenerable"|"keep"
  local p="$1"
  if [ ! -e "${p}" ]; then ok "${p}: not present"; return; fi
  if git check-ignore -q "${p}" 2>/dev/null; then ok "${p}: present, ignored by git"; else finding "${p}: present and NOT ignored by git"; fi
  local tracked
  tracked="$(git ls-files -- "${p}" 2>/dev/null)"
  if [ -n "${tracked}" ]; then
    if [ "${MODE}" = "check" ]; then
      finding "${p}: TRACKED by git (would be committed): $(echo "${tracked}" | tr '\n' ' ')"
    else
      git rm -r -q --cached -- "${p}" && fixed "${p}: untracked (file kept on disk). Commit this change."
    fi
  fi
}
while IFS= read -r p; do [ -n "${p}" ] && check_generated "${p}" regenerable; done <<EOF
${REGENERABLE}
EOF
while IFS= read -r p; do [ -n "${p}" ] && check_generated "${p}" keep; done <<EOF
${KEEP}
EOF

# ---------------------------------------------------------------- 4. purge rendered files
if [ "${PURGE}" = "1" ] && [ "${MODE}" != "check" ]; then
  section "4. Purge rendered manifests"
  TO_DELETE=""
  while IFS= read -r p; do [ -n "${p}" ] && [ -e "${p}" ] && TO_DELETE="${TO_DELETE} ${p}"; done <<EOF
${REGENERABLE}
EOF
  if [ -z "${TO_DELETE}" ]; then
    ok "nothing to purge"
  else
    echo "  Will delete:${TO_DELETE}"
    if [ "${YES}" = "1" ]; then REPLY="y"; else printf '  Delete these? They are regenerated by the labs. [y/N] '; read -r REPLY; fi
    case "${REPLY}" in
      y|Y) for p in ${TO_DELETE}; do rm -rf -- "${p}" && fixed "deleted ${p}"; done ;;
      *) warn "purge skipped" ;;
    esac
  fi
  ok "kept (ignored by git, needed until the cleanup): tls/, terraform.tfvars, terraform.tfstate, .terraform/"
fi

# ---------------------------------------------------------------- 5. content scan
section "5. Content scan of every file git would commit"
FILES="$(mktemp)"; trap 'rm -f "${FILES}"' EXIT
{ git ls-files; git ls-files --others --exclude-standard; } | sort -u \
  | grep -v -E '^scripts/sanitize\.sh$' > "${FILES}"

scan() {  # $1 label, $2 ERE, $3 optional ERE to exclude from the matched text, $4 "finding"|"warn"
  local label="$1" re="$2" exclude="${3:-}" level="${4:-finding}" hits
  hits="$(tr '\n' '\0' < "${FILES}" | xargs -0 grep -nIoE -e "${re}" -- 2>/dev/null || true)"
  if [ -n "${exclude}" ] && [ -n "${hits}" ]; then hits="$(printf '%s\n' "${hits}" | grep -vE "${exclude}" || true)"; fi
  if [ -z "${hits}" ]; then ok "${label}: none"; return; fi
  local n; n="$(printf '%s\n' "${hits}" | wc -l | tr -d ' ')"
  if [ "${level}" = "warn" ]; then warn "${label}: ${n} hit(s), review them:"; else finding "${label}: ${n} hit(s), edit these lines:"; fi
  printf '%s\n' "${hits}" | head -20 | sed 's/^/            /'
  [ "${n}" -gt 20 ] && echo "            ... $((n - 20)) more"
}

for ID in ${IDS}; do scan "project ID ${ID}" "${ID}"; done
scan "project numbers" '(service-[0-9]{12}@|projects/[0-9]{12}([^0-9]|$)|project[_ ]?number[^0-9]{0,6}[0-9]{12})'
scan "e-mail addresses" '[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}' ':[^:]*@(example\.com|users\.noreply\.github\.com)$'
# Public IPv4 addresses. Allowed: RFC 1918, link-local, loopback, CGNAT, unspecified, and the Google
# ranges the labs document (load balancer proxies and health checks, IAP, restricted VIP).
scan "public IP addresses" '([0-9]{1,3}\.){3}[0-9]{1,3}' \
  ':(10\.|172\.(1[6-9]|2[0-9]|3[01])\.|192\.168\.|169\.254\.|127\.|100\.64\.|0\.0\.0\.0|35\.191\.0\.0|130\.211\.0\.0|35\.235\.240\.0|199\.36\.153\.(4|8)|209\.85\.(152|204)\.0|35\.199\.192\.0|35\.190\.247\.13)[0-9.]*$'
scan "private keys" '-----BEGIN [A-Z ]*PRIVATE KEY-----'
scan "Google credentials (API keys, OAuth secrets, tokens, service account keys)" '(AIza[0-9A-Za-z_-]{35}|GOCSPX-[0-9A-Za-z_-]+|ya29\.[0-9A-Za-z_-]+|"private_key_id"|"type": *"service_account"|1//0[0-9A-Za-z_-]{20,})'
scan "kubeconfig DNS endpoints" 'gke-[0-9a-f]{40}-[0-9]{12}\.[a-z0-9-]+\.gke\.goog'
scan "cluster-generated resource names (identify your cluster; usually from pasted output)" '(gkegw1-[a-z0-9]{4}-|k8s1-[0-9a-f]{8}-|gke-[a-z0-9-]+-[0-9a-f]{8}-(node|all|vms|[a-z0-9]{4}\b))' '' warn

# ---------------------------------------------------------------- summary
section "Summary"
echo "  mode=${MODE}  fixed=${FIXED}  warnings=${WARNINGS}  findings=${FINDINGS}"
if [ "${FINDINGS}" -gt 0 ]; then
  echo "  Findings need a manual edit (or, in --check mode, a run without --check). Nothing has been committed."
  exit 1
fi
echo "  The working tree is safe to commit. Review 'git status' and 'git diff' before you do."
exit 0
